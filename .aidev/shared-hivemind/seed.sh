#!/usr/bin/env bash
# Seeds one template of the shared hivemind service: run by seeder.sh in the
# `seeder` container (hivemind's AIDEV runtime image), which shares the
# `hivemind` container's network namespace and reaches PostgreSQL on 127.0.0.1.
#
#   seed.sh REVISION COMMIT
#
# 1. Fetches hivemind at COMMIT (with the reputation_tracker and hafah
#    submodules) from HIVEMIND_SHARED_REMOTE and refuses it unless its
#    update_db_patchlevel.sql yields REVISION.
# 2. Clones haf_template (HAF's 5M replay, frozen by serve.sh) into seed_<REVISION>.
# 3. Installs and syncs hivemind there the way CI's `sync` job does
#    (docker/docker-compose-sync.yml: the hivemind image's `setup --with-apps
#    --add-mocks=true`, then reputation_tracker's process_blocks.sh alongside
#    `hive sync` to block 5000024 with --community-start-block 4998000), from the
#    fetched source instead of the image.
# 4. Renames it hivemind_<REVISION>, freezes it as a template no one may connect
#    to and records it in hivemind_shared.templates.
#
# CI's PostgreSQL tuning (ALTER SYSTEM fsync = off, …) is left out: it would
# apply to the whole cluster serving live clones, and changes no synced data.
#
# Environment: HIVEMIND_SHARED_REMOTE, HAF_FIXTURE_COMMIT.
set -euo pipefail

rev="${1:?usage: $0 REVISION COMMIT}"
commit="${2:?usage: $0 REVISION COMMIT}"
remote="${HIVEMIND_SHARED_REMOTE:?HIVEMIND_SHARED_REMOTE must name the hivemind repository to fetch}"
haf_commit="${HAF_FIXTURE_COMMIT:?}"
here="$(cd "$(dirname "$0")" && pwd -P)"

[[ "$rev" =~ ^[0-9a-f]{40}$ ]] || { echo "revision must be 40 hex digits, got '$rev'" >&2; exit 1; }
[[ "$commit" =~ ^[0-9a-f]{40}$ ]] || { echo "commit must be a full 40-character SHA, got '$commit'" >&2; exit 1; }

# docker/docker-compose-sync.yml and .gitlab-ci.yml `sync`.
MAX_BLOCK=5000024
COMMUNITY_START_BLOCK=4998000
REPTRACKER_SCHEMA=reptracker_app

PG=postgresql://postgres@127.0.0.1:5432
seed_db="seed_$rev"
template="hivemind_$rev"
ADMIN_URL="postgresql://haf_admin@127.0.0.1:5432/$seed_db"
USER_URL="postgresql://hivemind@127.0.0.1:5432/$seed_db"

work="$(mktemp -d)"
rt_pid=""
cleanup() {
    [ -n "$rt_pid" ] && kill "$rt_pid" 2>/dev/null
    rm -rf "$work"
}
trap cleanup EXIT

psql_pg() {
    psql -X -q -v ON_ERROR_STOP=1 "$@"
}

echo "== fetching hivemind $commit"
src="$work/src"
git init -q "$src"
git -C "$src" remote add origin "$remote"
git -C "$src" fetch -q --depth 1 origin "$commit"
git -C "$src" checkout -q --detach FETCH_HEAD
git -C "$src" submodule update -q --init --depth 1 reputation_tracker hafah \
    || git -C "$src" submodule update -q --init reputation_tracker hafah
actual="$(python3 "$here/shared_fixture.py" revision "$src/hive/db/sql_scripts/upgrade/update_db_patchlevel.sql")"
if [ "$actual" != "$rev" ]; then
    echo "commit $commit yields schema revision $actual, not $rev" >&2
    exit 1
fi
# hive/_version.py is generated by versioningit when the package is installed;
# hive runs from the source here.
printf "__version__ = '0.0.0+aidev'\n__git_revision__ = '%s'\n__git_revision_date__ = '%s'\n" \
    "$commit" "$(git -C "$src" log -1 --format=%cI)" > "$src/hive/_version.py"
# scripts/ci/add-mocks-to-db.sh runs the `mocker` console script.
mkdir -p "$work/bin"
cat > "$work/bin/mocker" <<'MOCKER'
#!/bin/sh
exec python3 -c 'import sys; from hive.indexer.mocking.populate_haf_with_mocked_data import main; sys.argv[0] = "mocker"; main()' "$@"
MOCKER
chmod +x "$work/bin/mocker"
export PATH="$work/bin:$PATH" PYTHONPATH="$src"

echo "== cloning haf_template into $seed_db"
psql_pg -d "$PG/postgres" -c "drop database if exists $seed_db with (force)" \
    -c "create database $seed_db owner haf_admin template haf_template strategy file_copy"

echo "== installing (the hivemind image's setup --with-apps --add-mocks=true)"
cd "$src"
bash scripts/setup_postgres.sh --postgres-url="$ADMIN_URL"
(cd reputation_tracker && bash scripts/install_app.sh --postgres-url="$ADMIN_URL" \
    --schema="$REPTRACKER_SCHEMA" --is_forking=false)
(cd hafah && bash scripts/install_app.sh --postgres-url="$ADMIN_URL")
bash scripts/install_app.sh --reptracker-schema-name="$REPTRACKER_SCHEMA" --postgres-url="$ADMIN_URL"
bash scripts/ci/add-mocks-to-db.sh --postgres-url="$ADMIN_URL"
python3 -m hive.cli build_schema --database-url="$ADMIN_URL"

echo "== syncing to $MAX_BLOCK"
bash reputation_tracker/scripts/process_blocks.sh --stop-at-block="$MAX_BLOCK" --postgres-url="$USER_URL" &
rt_pid=$!
python3 -m hive.cli sync \
    --log-mask-sensitive-data \
    --pid-file "$work/hive_sync.pid" \
    --test-max-block="$MAX_BLOCK" \
    --test-profile=False \
    --prometheus-port 11011 \
    --database-url="$USER_URL" \
    --community-start-block "$COMMUNITY_START_BLOCK" \
    --reptracker-schema-name="$REPTRACKER_SCHEMA" \
    --swagger-url="{hivemind-host}"
wait "$rt_pid"
rt_pid=""

head_block="$(psql_pg -d "$USER_URL" -Atc 'select last_completed_block_num from hivemind_app.hive_state')"
if [[ ! "$head_block" =~ ^[0-9]+$ ]] || [ "$head_block" -lt "$MAX_BLOCK" ]; then
    echo "hivemind stopped at block '$head_block', short of $MAX_BLOCK; not freezing it" >&2
    exit 1
fi

echo "== freezing $template (head block $head_block)"
cd /
psql_pg -d "$PG/postgres" <<SQL
select pg_terminate_backend(pid) from pg_stat_activity where datname = '$seed_db' and pid <> pg_backend_pid();
select 'alter database $template is_template false' where exists (select 1 from pg_database where datname = '$template')
\gexec
drop database if exists $template with (force);
alter database $seed_db rename to $template;
alter database $template is_template true allow_connections false;
SQL
psql_pg -d "$PG/hivemind_shared" -v rev="$rev" -v template="$template" -v haf="$haf_commit" \
    -v commit="$commit" -v head="$head_block" <<'SQL'
insert into hivemind_shared.templates (revision, database_name, haf_commit, hivemind_commit, head_block)
values (:'rev', :'template', :'haf', :'commit', :'head')
on conflict (revision) do update
    set database_name = excluded.database_name, haf_commit = excluded.haf_commit,
        hivemind_commit = excluded.hivemind_commit, head_block = excluded.head_block, seeded_at = now();
SQL
echo "seeded $template from hivemind $commit"
